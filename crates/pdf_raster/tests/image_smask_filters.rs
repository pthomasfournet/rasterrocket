/// A soft mask stored as a three-component JPEG is read as its luminosity
/// (PDF §11.3.5.3), not rejected.
#[test]
fn three_component_dct_smask_is_read_as_luminosity() {
    let (left, right) = masked_halves(
        "/BitsPerComponent 8 /Filter /DCTDecode",
        JPEG_2X1_WHITE_BLACK,
    );
    assert!(
        left < 16 && right > 239,
        "the image must show on the left only; (left, right) gray = ({left}, {right})"
    );
}
