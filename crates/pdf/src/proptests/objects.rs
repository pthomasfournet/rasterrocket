//! The object parser reads back what a reference serialiser produces.
//!
//! The serialiser writes a generated [`Object`] in one of the many
//! spellings ISO 32000-2 §7.3 allows (separators and comments, optional
//! where a delimiter bounds a token, name and string escapes, octal escapes
//! of one to three digits and line continuations, hex digit case and
//! whitespace, number forms), choosing among them from a byte stream that
//! proptest generates and shrinks with the object.  It also writes two
//! spellings a conforming writer may not use and the parser accepts:
//! reals with an exponent (§7.3.3 has none), for very small and very
//! large values, and `#00` in names (§7.3.5 excludes NUL).  [`parse_object`]
//! must return the object and stop exactly at its end.

use proptest::prelude::*;

use super::config;
use crate::dictionary::Dictionary;
use crate::object::{MAX_OBJECT_NUMBER, Object, Stream, StringFormat, parse_object};

/// Spelling choices, drawn cyclically from generated bytes.
struct Style<'a> {
    bytes: &'a [u8],
    at: usize,
}

impl Style<'_> {
    /// A choice in `0..n`.
    fn pick(&mut self, n: u8) -> u8 {
        if self.bytes.is_empty() {
            return 0;
        }
        let b = self.bytes[self.at % self.bytes.len()];
        self.at += 1;
        b % n
    }

    fn flip(&mut self) -> bool {
        self.pick(2) == 1
    }
}

/// A non-empty run of whitespace or a comment.
fn sep(out: &mut Vec<u8>, style: &mut Style<'_>) {
    const SEPS: [&[u8]; 8] = [
        b" ",
        b"\n",
        b"\r\n",
        b"\r",
        b"\t",
        b"\x0c",
        b"\0",
        b" % a comment (with [delimiters] <<>>)\n",
    ];
    out.extend_from_slice(SEPS[usize::from(style.pick(8))]);
}

/// An optional separator, where a delimiter already ends the token before.
fn opt_sep(out: &mut Vec<u8>, style: &mut Style<'_>) {
    if style.flip() {
        sep(out, style);
    }
}

/// Appends `token` after a separator, which is optional when the text so far
/// ends with a closing delimiter or `token` starts with a delimiter
/// (ISO 32000-2 §7.2.3).  A trailing `/` or `<` does not count: an empty
/// name followed by a regular byte reads as one longer name, and `<` is
/// only ever followed here by a token that opens with a delimiter.
fn join(out: &mut Vec<u8>, token: &[u8], style: &mut Style<'_>) {
    let closed = matches!(out.last(), Some(b')' | b'>' | b']'));
    let opens = matches!(
        token.first(),
        Some(b'/' | b'(' | b')' | b'<' | b'>' | b'[' | b']')
    );
    if closed || opens {
        opt_sep(out, style);
    } else {
        sep(out, style);
    }
    out.extend_from_slice(token);
}

/// `obj` as written by [`write_object`], on its own.
fn written(obj: &Object, style: &mut Style<'_>) -> Vec<u8> {
    let mut token = Vec::new();
    write_object(&mut token, obj, style);
    token
}

fn hex_digit(nibble: u8, upper: bool) -> u8 {
    let digits = if upper {
        b"0123456789ABCDEF"
    } else {
        b"0123456789abcdef"
    };
    digits[usize::from(nibble)]
}

/// A byte that may appear unescaped in a name: printable ASCII other than
/// the delimiters and `#` (ISO 32000-2 §7.3.5).
const fn is_regular_name_byte(b: u8) -> bool {
    matches!(b, 0x21..=0x7e)
        && !matches!(
            b,
            b'(' | b')' | b'<' | b'>' | b'[' | b']' | b'{' | b'}' | b'/' | b'%' | b'#'
        )
}

/// `/name`, each byte verbatim or as `#xx`; a NUL byte is written `#00`,
/// which the parser accepts beyond §7.3.5.
fn write_name(out: &mut Vec<u8>, name: &[u8], style: &mut Style<'_>) {
    out.push(b'/');
    for &b in name {
        if is_regular_name_byte(b) && style.pick(4) != 0 {
            out.push(b);
        } else {
            let upper = style.flip();
            out.extend_from_slice(&[b'#', hex_digit(b >> 4, upper), hex_digit(b & 15, upper)]);
        }
    }
}

fn write_literal(out: &mut Vec<u8>, s: &[u8], style: &mut Style<'_>) {
    out.push(b'(');
    for (i, &b) in s.iter().enumerate() {
        // A backslash before an EOL is a line continuation and adds nothing.
        // A bare CR continuation before an LF would read as one CRLF.
        if style.pick(8) == 0 {
            let eols = if b == b'\n' { 2 } else { 3 };
            out.extend_from_slice(
                [&b"\\\n"[..], b"\\\r\n", b"\\\r"][usize::from(style.pick(eols))],
            );
        }
        let named = match b {
            b'\n' => Some(b'n'),
            b'\r' => Some(b'r'),
            b'\t' => Some(b't'),
            0x08 => Some(b'b'),
            0x0c => Some(b'f'),
            b'(' | b')' | b'\\' => Some(b),
            _ => None,
        };
        let must_escape = matches!(b, b'(' | b')' | b'\\' | b'\r');
        match style.pick(3) {
            0 if !must_escape => out.push(b),
            1 if named.is_some() => out.extend_from_slice(&[b'\\', named.unwrap_or(b)]),
            _ => {
                // An escape may have fewer than three digits unless an
                // octal digit follows it (§7.3.4.2).
                let fewest: u8 = match b {
                    0..8 => 1,
                    8..64 => 2,
                    _ => 3,
                };
                let digits = usize::from(if matches!(s.get(i + 1), Some(b'0'..=b'7')) {
                    3
                } else {
                    fewest + style.pick(4 - fewest)
                });
                out.extend_from_slice(format!("\\{b:0digits$o}").as_bytes());
            }
        }
    }
    out.push(b')');
}

fn write_hex(out: &mut Vec<u8>, s: &[u8], style: &mut Style<'_>) {
    out.push(b'<');
    for (i, &b) in s.iter().enumerate() {
        let upper = style.flip();
        opt_ws(out, style);
        out.push(hex_digit(b >> 4, upper));
        opt_ws(out, style);
        // A final digit pair ending in 0 may drop the 0 (§7.3.4.3).
        if !(i + 1 == s.len() && b.trailing_zeros() >= 4 && style.flip()) {
            out.push(hex_digit(b & 15, upper));
        }
    }
    opt_ws(out, style);
    out.push(b'>');
}

/// Optional whitespace inside a hex string, where comments are not allowed.
fn opt_ws(out: &mut Vec<u8>, style: &mut Style<'_>) {
    if style.pick(4) == 0 {
        out.push(b" \n\r\t"[usize::from(style.pick(4))]);
    }
}

fn write_integer(out: &mut Vec<u8>, n: i64, style: &mut Style<'_>) {
    let digits = n.unsigned_abs().to_string();
    if n < 0 {
        out.push(b'-');
    } else if style.pick(4) == 0 {
        out.push(b'+');
    }
    for _ in 0..style.pick(3) {
        out.push(b'0');
    }
    out.extend_from_slice(digits.as_bytes());
}

/// A real in the shortest form that reads back exactly, as `ddd.ddd`,
/// `.ddd`, `ddd.` or, for very small and very large values, with an exponent,
/// which the parser accepts beyond §7.3.3.
fn write_real(out: &mut Vec<u8>, r: f32, style: &mut Style<'_>) {
    let text = format!("{r:?}");
    let mut text = text.as_str();
    if r.is_sign_positive() && style.pick(4) == 0 {
        out.push(b'+');
    }
    // `0.5` may be written `.5`, `-0.5` `-.5`.
    if style.flip() {
        if let Some(rest) = text.strip_prefix("0.") {
            out.push(b'.');
            text = rest;
        } else if let Some(rest) = text.strip_prefix("-0.") {
            out.extend_from_slice(b"-.");
            text = rest;
        }
    }
    // `5.0` may be written `5.`, unless that leaves no digit.
    match text.strip_suffix(".0") {
        Some(int) if style.flip() && int.bytes().any(|b| b.is_ascii_digit()) => {
            out.extend_from_slice(int.as_bytes());
            out.push(b'.');
        }
        _ => out.extend_from_slice(text.as_bytes()),
    }
}

fn write_dict(out: &mut Vec<u8>, dict: &Dictionary, style: &mut Style<'_>) {
    out.extend_from_slice(b"<<");
    for (key, value) in dict {
        let mut name = Vec::new();
        write_name(&mut name, key, style);
        join(out, &name, style);
        let value = written(value, style);
        join(out, &value, style);
    }
    join(out, b">>", style);
}

fn write_object(out: &mut Vec<u8>, obj: &Object, style: &mut Style<'_>) {
    match obj {
        Object::Null => out.extend_from_slice(b"null"),
        Object::Boolean(b) => out.extend_from_slice(if *b { b"true" } else { b"false" }),
        Object::Integer(n) => write_integer(out, *n, style),
        Object::Real(r) => write_real(out, *r, style),
        Object::Name(n) => write_name(out, n, style),
        Object::String(s, StringFormat::Literal) => write_literal(out, s, style),
        Object::String(s, StringFormat::Hexadecimal) => write_hex(out, s, style),
        Object::Array(items) => {
            out.push(b'[');
            for item in items {
                let item = written(item, style);
                join(out, &item, style);
            }
            join(out, b"]", style);
        }
        Object::Dictionary(d) => write_dict(out, d, style),
        Object::Stream(s) => {
            write_dict(out, &s.dict, style);
            join(out, b"stream", style);
            out.extend_from_slice(if style.flip() { b"\r\n" } else { b"\n" });
            out.extend_from_slice(&s.content);
            out.extend_from_slice([&b"\n"[..], b"\r\n", b"\r"][usize::from(style.pick(3))]);
            out.extend_from_slice(b"endstream");
        }
        Object::Reference((num, generation)) => {
            out.extend_from_slice(num.to_string().as_bytes());
            sep(out, style);
            out.extend_from_slice(generation.to_string().as_bytes());
            sep(out, style);
            out.push(b'R');
        }
    }
}

fn name() -> impl Strategy<Value = Vec<u8>> {
    prop::collection::vec(any::<u8>(), 0..12)
}

fn real() -> impl Strategy<Value = f32> {
    use prop::num::f32::{NEGATIVE, NORMAL, POSITIVE, SUBNORMAL, ZERO};
    POSITIVE | NEGATIVE | NORMAL | SUBNORMAL | ZERO
}

/// Any object other than a stream, nested up to four deep.
fn value() -> impl Strategy<Value = Object> {
    let leaf = prop_oneof![
        Just(Object::Null),
        any::<bool>().prop_map(Object::Boolean),
        any::<i64>().prop_map(Object::Integer),
        // Small integers, so that `n g R`-like runs of integers occur.
        (0i64..4).prop_map(Object::Integer),
        real().prop_map(Object::Real),
        name().prop_map(Object::Name),
        (prop::collection::vec(any::<u8>(), 0..24), any::<bool>()).prop_map(|(s, hex)| {
            let format = if hex {
                StringFormat::Hexadecimal
            } else {
                StringFormat::Literal
            };
            Object::String(s, format)
        }),
        // A reference names an object number; larger numbers are integers.
        (0..=MAX_OBJECT_NUMBER, any::<u16>()).prop_map(Object::Reference),
    ];
    leaf.prop_recursive(4, 48, 6, |inner| {
        prop_oneof![
            prop::collection::vec(inner.clone(), 0..6).prop_map(Object::Array),
            prop::collection::vec((name(), inner), 0..6)
                .prop_map(|entries| Object::Dictionary(entries.into_iter().collect())),
        ]
    })
}

/// A stream whose dictionary's direct `/Length` gives its body's size.
fn stream() -> impl Strategy<Value = Object> {
    (
        prop::collection::vec((name(), value()), 0..4),
        prop::collection::vec(any::<u8>(), 0..512),
    )
        .prop_map(|(entries, content)| {
            let mut dict: Dictionary = entries.into_iter().collect();
            let len = i64::try_from(content.len()).expect("content length fits i64");
            dict.set("Length", Object::Integer(len));
            Object::Stream(Stream::new(dict, content))
        })
}

proptest! {
    #![proptest_config(config(2048))]

    /// Every spelling of an object parses back to it, and the parser stops
    /// at the object's last byte.
    #[test]
    fn written_objects_parse_back(
        obj in prop_oneof![4 => value(), 1 => stream()],
        style in prop::collection::vec(any::<u8>(), 0..64),
    ) {
        let mut text = Vec::new();
        write_object(&mut text, &obj, &mut Style { bytes: &style, at: 0 });
        let end = text.len();
        text.extend_from_slice(b"\nendobj\n");
        let mut pos = 0;
        let parsed = parse_object(&text, &mut pos);
        prop_assert_eq!(parsed.as_ref(), Some(&obj), "text {:?}", String::from_utf8_lossy(&text));
        prop_assert_eq!(pos, end);
    }

    /// A stream whose `/Length` is an indirect reference, unresolvable while
    /// parsing, reads its body up to the EOL before `endstream endobj`.
    #[test]
    fn stream_with_indirect_length_finds_its_end(
        content in prop::collection::vec(any::<u8>(), 0..512)
            .prop_filter("no keyword or trailing CR in the body", |c| {
                c.last() != Some(&b'\r')
                    && !c.windows(9).any(|w| w == b"endstream")
            }),
        eol in prop_oneof![Just(&b"\n"[..]), Just(&b"\r\n"[..]), Just(&b"\r"[..])],
    ) {
        let mut text = b"<< /Length 12 0 R >>\nstream\n".to_vec();
        text.extend_from_slice(&content);
        text.extend_from_slice(eol);
        text.extend_from_slice(b"endstream\nendobj\n");
        let mut pos = 0;
        let parsed = parse_object(&text, &mut pos);
        let Some(Object::Stream(s)) = parsed else {
            return Err(TestCaseError::fail(format!("not a stream: {parsed:?}")));
        };
        prop_assert_eq!(s.content, content);
        prop_assert_eq!(&text[pos..], b"\nendobj\n");
    }
}
